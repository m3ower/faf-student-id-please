"""Build the shared collection from all eight service collections without variable collisions."""

import argparse
import copy
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SERVICES = ["player", "session", "applicant", "university-record", "credential",
            "server-rules", "moderation", "discord-dms"]
OUTPUT = ROOT / "postman/Student-ID-Please-Lab-1.postman_collection.json"


def build():
    result = {
        "info": {
            "name": "Student ID - Shared Lab 4 service checks",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
            "description": "Generated by scripts/build_shared_postman.py from all eight service collections. "
                           "The historical filename is retained for existing imports. Run service folders "
                           "individually with their documented prerequisites; optional shift, replay, logs "
                           "and Broker checks require separate setup. Variables are prefixed per service; "
                           "only baseUrl and log exporter settings are shared. Native gRPC uses messaging.proto. "
                           "See README.md and ../docs/lab4-configuration-review.md. Never export runtime secrets.",
        },
        "variable": [],
        "item": [],
    }
    common = {"baseUrl", "logDownloadUrl", "logDownloadToken"}
    declared = set()
    for service in SERVICES:
        source = json.loads((ROOT / f"postman/{service}-service.postman_collection.json").read_text(encoding="utf-8"))
        prefix = service.replace("-", "_") + "_"
        names = {v["key"]: v["key"] if v["key"] in common else prefix + v["key"]
                 for v in source.get("variable", [])}

        def transform(value):
            if isinstance(value, str):
                return re.sub(r"\{\{([^{}]+)\}\}",
                              lambda m: "{{" + names.get(m[1], m[1]) + "}}", value)
            if isinstance(value, list):
                return [transform(v) for v in value]
            if isinstance(value, dict):
                return {k: transform(v) for k, v in value.items()}
            return value

        def scripts(node):
            for event in node.get("event", []):
                lines = event["script"].get("exec", [])
                text = lines if isinstance(lines, str) else "\n".join(lines)
                # Scope accessor arguments, including computed keys. Leave JSON field
                # names and response assertions unchanged. Common settings stay shared.
                text = re.sub(r"pm\.(collectionVariables|variables|environment|globals)\.(get|set|unset|has)\(",
                              lambda m: "__sharedStores." + m[1] + "." + m[2] + "(", text)
                prelude = [
                    "const __sharedKey = key => " + json.dumps(prefix) + " + key;",
                    "const __sharedCommon = new Set(" + json.dumps(sorted(common)) + ");",
                    "const __sharedStores = {};",
                    "['collectionVariables','variables','environment','globals'].forEach(store => {",
                    "  __sharedStores[store] = {};",
                    "  ['get','set','unset','has'].forEach(method => {",
                    "    __sharedStores[store][method] = (key, ...args) => pm[store][method](__sharedCommon.has(key) ? key : __sharedKey(key), ...args);",
                    "  });",
                    "});",
                ]
                event["script"]["exec"] = prelude + text.splitlines()
            for item in node.get("item", []):
                scripts(item)

        folder = transform({"name": service + " service", "description": source["info"].get("description", ""),
                            "item": copy.deepcopy(source["item"])})
        for key in ["auth", "event"]:
            if key in source:
                folder[key] = transform(copy.deepcopy(source[key]))
        scripts(folder)
        result["item"].append(folder)
        for variable in source.get("variable", []):
            key = names[variable["key"]]
            if key not in declared:
                result["variable"].append({**transform(variable), "key": key})
                declared.add(key)
    result["item"].append({
        "name": "Optional - System log download",
        "description": "Run the host log exporter for the exact project and both Compose files. "
                       "This downloads all configured running services, including Message Broker.",
        "item": [{
            "name": "Download system logs",
            "request": {
                "method": "GET",
                "url": "{{logDownloadUrl}}/internal/v1/logs?since=15m&tail=200",
                "auth": {"type": "bearer", "bearer": [
                    {"key": "token", "value": "{{logDownloadToken}}", "type": "string"}
                ]},
            },
            "event": [{"listen": "test", "script": {"type": "text/javascript", "exec": [
                "pm.test('System logs download succeeds', () => pm.response.to.have.status(200));",
                "pm.test('Download is an attachment', () => pm.expect(pm.response.headers.get('Content-Disposition')).to.include('attachment;'));",
            ]}}],
        }],
    })
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--owned-copy", action="store_true",
                        help="also refresh/check the historical Applicant repository's two-service copy")
    args = parser.parse_args()
    expected = build()
    outputs = [(OUTPUT, expected)]
    if args.owned_copy:
        owned = copy.deepcopy(expected)
        owned["info"]["name"] = "Student ID - Applicant and University Record Lab 4 checks"
        owned["info"]["description"] = "Generated from the CPR's current Applicant and University Record collections. " \
            "Run folders separately with real Session membership and private credentials. Native gRPC uses the shared " \
            "messaging.proto; HTTP compatibility is not native gRPC acceptance. Source and setup: " \
            "https://github.com/m3ower/faf-student-id-please/tree/dev/postman"
        owned["item"] = [item for item in owned["item"]
                         if item["name"] in {"applicant service", "university-record service"}]
        owned["variable"] = [v for v in owned["variable"]
                             if v["key"] in {"baseUrl", "logDownloadUrl", "logDownloadToken"}
                             or v["key"].startswith(("applicant_", "university_record_"))]
        outputs.append((ROOT / "services/applicant-service/postman/Student-ID-Please-Lab-1.postman_collection.json", owned))
    if args.check:
        for path, data in outputs:
            if json.loads(path.read_text(encoding="utf-8")) != data:
                raise SystemExit(str(path.relative_to(ROOT)) + " is stale; run scripts/build_shared_postman.py with the same options")
        print("Shared Postman collection matches all eight service collections")
    else:
        for path, data in outputs:
            path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
            print("Updated " + str(path.relative_to(ROOT)))


if __name__ == "__main__":
    main()
